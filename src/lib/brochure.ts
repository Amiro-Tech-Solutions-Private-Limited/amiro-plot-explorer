import type { Flat } from '../data/types';
import { PROJECT, unitOf } from '../data/project';
import { priceOf } from './pricing';
import { formatPrice, feetInches, ordinal } from './format';
import { FACING_LONG, flatFrame, FLAT_D, FLAT_W, BALC_D } from './geometry';
import { vastuOf, roomDirection, DIR_LONG } from './vastu';
import { flatXform } from './interiorFrame';

const rs = (n: number) => `Rs. ${Math.round(n).toLocaleString('en-IN')}`;

export async function downloadBrochure(flat: Flat) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const u = unitOf(flat);
  const p = priceOf(flat);
  const v = vastuOf(flat);

  doc.setFillColor(8, 83, 59);
  doc.rect(0, 0, 210, 28, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text(PROJECT.name, 14, 13);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(PROJECT.locality, 14, 20);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text(`Flat ${flat.id}`, 196, 17, { align: 'right' });

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(13);
  doc.text(`${u.label} · ${FACING_LONG[flat.facing]} facing · ${ordinal(flat.floor)} floor`, 14, 40);

  const facts: [string, string][] = [
    ['Carpet area', `${u.carpet.toLocaleString('en-IN')} sq ft`],
    ['Built-up area', `${u.builtUp.toLocaleString('en-IN')} sq ft`],
    ['Super built-up', `${u.superBuiltUp.toLocaleString('en-IN')} sq ft`],
    ['View', flat.view.join(', ')],
    ['Balconies', String(u.balconies)],
    ['Car parks', String(u.carParks)],
    ['Vastu score', `${v.stars} / 5`],
    ['Status', flat.status[0].toUpperCase() + flat.status.slice(1)],
  ];
  doc.setFontSize(10);
  facts.forEach(([k, val], i) => {
    const x = 14 + (i % 2) * 92;
    const y = 50 + Math.floor(i / 2) * 7;
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139);
    doc.text(k, x, y);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30, 41, 59);
    doc.text(val, x + 36, y);
  });

  // Floor plan
  const fr = flatFrame(flat.index);
  const layout = flatXform(flat).layout;
  const ox = 14;
  const oy = 86;
  const k = 6.2;
  doc.setDrawColor(203, 213, 225);
  doc.setFontSize(7);
  for (const r of layout.rooms) {
    doc.setFillColor(r.kind === 'balcony' ? 225 : 241, r.kind === 'balcony' ? 218 : 245, r.kind === 'balcony' ? 208 : 249);
    doc.rect(ox + r.x * k, oy + r.y * k, r.w * k, r.h * k, 'FD');
    doc.setTextColor(30, 41, 59);
    doc.text(r.name, ox + (r.x + r.w / 2) * k, oy + (r.y + r.h / 2) * k, { align: 'center' });
  }
  doc.setDrawColor(31, 41, 55);
  doc.setLineWidth(0.6);
  for (const s of layout.segs) if (s.kind === 'wall') doc.line(ox + s.x1 * k, oy + s.y1 * k, ox + s.x2 * k, oy + s.y2 * k);
  doc.setLineWidth(0.2);
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(`${feetInches(FLAT_W)} x ${feetInches(FLAT_D)} (indicative, not to scale)`, ox, oy + (FLAT_D + BALC_D) * k + 6);

  // Price breakdown
  const px = 112;
  let py = 92;
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(30, 41, 59);
  doc.text('Price breakdown', px, py - 6);
  doc.setFontSize(9);
  const lines: [string, number][] = [
    [`Base (${u.superBuiltUp} x Rs. ${flat.baseRate})`, p.base],
    ['Floor rise', p.floorRise],
    ['PLC (corner / view)', p.plc],
    ['Car parking', p.parking],
    ['Club membership', p.club],
    [`GST (${PROJECT.pricing.gstPct}%)`, p.gst],
    [`Stamp duty & reg. (${PROJECT.pricing.stampPct}%, est.)`, p.stamp],
  ];
  lines.forEach(([l, val]) => {
    doc.setFont('helvetica', 'normal');
    doc.text(l, px, py);
    doc.text(rs(val), 196, py, { align: 'right' });
    py += 6;
  });
  doc.setDrawColor(203, 213, 225);
  doc.line(px, py - 3, 196, py - 3);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('All-inclusive', px, py + 2);
  doc.text(formatPrice(p.total, true), 196, py + 2, { align: 'right' });

  // Room schedule
  let ry = 180;
  doc.setFontSize(12);
  doc.text('Room schedule', 14, ry);
  ry += 6;
  doc.setFontSize(9);
  for (const r of u.rooms) {
    doc.setFont('helvetica', 'normal');
    doc.text(r.level ? `${r.name} (upper level)` : r.name, 14, ry);
    doc.text(`${feetInches(r.w)} x ${feetInches(r.h)}`, 80, ry);
    if (!r.level) doc.text(DIR_LONG[roomDirection(flat, r)], 120, ry);
    ry += 5;
    if (ry > 280) break;
  }

  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.text(`${PROJECT.disclaimer} Generated by ${PROJECT.brand}.`, 14, 290, { maxWidth: 182 });

  doc.save(`NorthPark-${flat.id}.pdf`);
}
